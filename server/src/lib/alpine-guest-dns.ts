/** Repair only Alpine guests carrying our old duplicate DHCP registration. */
export const alpineGuestDnsRepairScript = `
if [ -f /etc/alpine-release ] && [ -f /var/lib/incudal/initialization-ready ] &&
  [ -f /usr/local/bin/incudal-required-init.sh ] &&
  grep -Fq 'rc-update add dhcpcd default' /usr/local/bin/incudal-required-init.sh &&
  grep -Eq '^[[:space:]]*iface[[:space:]]+eth0[[:space:]]+inet[[:space:]]+dhcp([[:space:]]|$)' /etc/network/interfaces; then
  # ifupdown already starts the per-interface DHCP client. Remove only our
  # redundant default registration; do not stop either live network process.
  if [ -L /etc/runlevels/default/dhcpcd ] &&
    [ "$(readlink -f /etc/runlevels/default/dhcpcd)" = /etc/init.d/dhcpcd ]; then
    rc-update del dhcpcd default >/dev/null
  fi
  # Two old dhcpcd processes can truncate their shared resolver output. Reuse
  # the existing DHCP lease's DNS only for an empty regular resolver file.
  # Customer nameservers and symlinks remain untouched.
  lease_dns=/run/dhcpcd/hook-state/resolv.conf/eth0.dhcp
  if [ -f /etc/resolv.conf ] && [ ! -L /etc/resolv.conf ] && [ ! -s /etc/resolv.conf ] &&
    [ -f "$lease_dns" ] && [ ! -L "$lease_dns" ] && grep -Eq '^nameserver [0-9.:a-fA-F]+$' "$lease_dns"; then
    resolver_tmp=$(mktemp /etc/resolv.conf.incudal.XXXXXX)
    printf '%s\\n' '# PayIncus recovered DHCP resolver' > "$resolver_tmp"
    awk '/^nameserver [0-9.:a-fA-F]+$/ { print }' "$lease_dns" >> "$resolver_tmp"
    chmod 0644 "$resolver_tmp"
    if [ ! -L /etc/resolv.conf ] && [ ! -s /etc/resolv.conf ]; then
      mv "$resolver_tmp" /etc/resolv.conf
    else
      rm "$resolver_tmp"
    fi
  fi
  # Use the distribution's resolver aggregator while old live clients finish
  # naturally. The next normal boot uses only the ifupdown-owned client.
  if [ -f /etc/resolv.conf ] && [ ! -L /etc/resolv.conf ] &&
    grep -Eq '^# (PayIncus recovered DHCP resolver|Generated by dhcpcd)' /etc/resolv.conf; then
    if ! command -v resolvconf >/dev/null; then
      timeout 15 apk add --no-cache openresolv || exit 76
    fi
    if grep -Fq '# PayIncus recovered DHCP resolver' /etc/resolv.conf; then
      resolvconf -a eth0.dhcp < /etc/resolv.conf
    fi
  fi
fi
`
